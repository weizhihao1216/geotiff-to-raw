static const double EARTH_RADIUS_KM = 6371.0;
static const double PI = 3.14159265358979323846;

GeoGazetteer& GeoGazetteer::Instance() {
    static GeoGazetteer instance;
    return instance;
}

GeoGazetteer::GeoGazetteer() {
    initBuiltinData();
}

double GeoGazetteer::calculateHaversineDistance(double lat1, double lon1, double lat2, double lon2) {
    double dLat = (lat2 - lat1) * PI / 180.0;
    double dLon = (lon2 - lon1) * PI / 180.0;

    double a = std::sin(dLat / 2.0) * std::sin(dLat / 2.0) +
               std::cos(lat1 * PI / 180.0) * std::cos(lat2 * PI / 180.0) *
               std::sin(dLon / 2.0) * std::sin(dLon / 2.0);

    double c = 2.0 * std::atan2(std::sqrt(a), std::sqrt(1.0 - a));
    return EARTH_RADIUS_KM * c;
}

