bool GeoGazetteer::FindNearestPlace(double lat, double lon, PlaceItem& outPlace, double& outDistanceKm, double maxDistKm) const {
    double minDistance = (std::numeric_limits<double>::max)();
    int bestIndex = -1;

    for (size_t i = 0; i < m_places.size(); ++i) {
        double dist = calculateHaversineDistance(lat, lon, m_places[i].lat, m_places[i].lon);
        if (dist < minDistance) {
            minDistance = dist;
            bestIndex = static_cast<int>(i);
        }
    }

    if (bestIndex >= 0 && minDistance <= maxDistKm) {
        outPlace = m_places[static_cast<size_t>(bestIndex)];
        outDistanceKm = minDistance;
        return true;
    }

    return false;
}

QString GeoGazetteer::FormatPlaceDescription(double lat, double lon) const {
    PlaceItem place;
    double distKm = 0.0;

    if (FindNearestPlace(lat, lon, place, distKm, 800.0)) {
        if (distKm < 15.0) {
            return QString("📍 %1 (%2)").arg(place.name, place.category);
        } else if (distKm < 100.0) {
            return QString("📍 %1 附近 (~%2km)").arg(place.name).arg(static_cast<int>(std::round(distKm)));
        } else {
            return QString("📍 %1 区域 (~%2km)").arg(place.name).arg(static_cast<int>(std::round(distKm)));
        }
    }
    return QString("📍 未知水域/陆地");
}

